    private void jButtonPrimeroActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonPrimeroActionPerformed
        Coche c = listaCoches.irAlPrimero();
        c.irAlPrimero();
        if (c.obtenerCocheActual() == c) {
            listaCoches.irAlPrimero();
        } else {
            jButtonPrimero.setEnabled(false);
        }
    }//GEN-LAST:event_jButtonPrimeroActionPerformed

    private void jToggleButtonAnteriorActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jToggleButtonAnteriorActionPerformed
        Coche c = listaCoches.irAlUltimo();
        if (listaCoches.obtenerCocheActual() != c) {
            listaCoches.retroceder();
        }
        
    }//GEN-LAST:event_jToggleButtonAnteriorActionPerformed

